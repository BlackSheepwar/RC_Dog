/**
 * @file svc_uart.h
 * @brief 串口链路服务：字节流→帧、帧队列、发送排队与 DMA 泵
 * @author 李嘉图
 * @date 2026-10-31
 *
 * @note 这一层是"串口怎么用"，不是"串口是什么"：
 *         - 从 BSP 取字节流，喂给 Svc_Proto 解包，成帧后放进帧队列；
 *         - 提供发送接口，把帧塞进发送队列，由发送任务逐帧交给 DMA；
 *         - 汇总每个端口的收发与异常计数，现场不接调试器也能看出问题。
 *
 *       线程模型（各占一个线程，互不阻塞）：
 *         RX 任务    : Svc_Uart_Rx_Poll()  等中断通知 → 排空所有端口 → 解包
 *         CMD 任务   : Svc_Uart_Frame_Get() 取一帧 → 交给 APP 命令表
 *         TX 任务    : Svc_Uart_Tx_Pump()  取一帧 → DMA 发出 → 等完成
 *
 *       队列与信号量全部由 CubeMX 在 freertos.c 中创建（UART_RX_Q、
 *       UART_TX_Q、UART_RX_BS、UART_TX_CS），本层只使用、不创建。
 */

#ifndef __Svc_Uart_H__
#define __Svc_Uart_H__

/*==============================================================================
 * 头文件包含
 *============================================================================*/
// 固定包含
#include <stdint.h>
#include "svc_proto.h"

/*==============================================================================
 * 宏定义与常量
 *============================================================================*/
/** @brief 帧队列深度（帧），满时丢最旧的一帧 */
#define SVC_UART_FRAME_DEPTH    8u
/** @brief 等待 DMA 发送完成的超时（ms） */
#define SVC_UART_TX_WAIT_MS     50
/** @brief 半帧超时（ms）：超过这个时间没有新字节，丢弃已收到的半帧 */
#define SVC_UART_FRAME_TIMEOUT_MS   50
/** @brief 接收轮询周期（ms）：没有中断通知时，最迟这么久处理一次新字节 */
#define SVC_UART_RX_POLL_MS     2

/*==============================================================================
 * 类型定义
 *============================================================================*/
/**
 * @brief 发送帧（已打包成线缆格式）
 * @note CubeMX 生成的 freertos.c 用 APP_TxFrame_t 创建 UART_TX_Q，
 *       那个名字是本类型的别名（见 app_uart.h），两边不会各存一份定义。
 */
typedef struct {
    uint8_t id;                          /* 目标端口编号，1 起 */
    uint8_t len;                         /* 帧总长 */
    uint8_t data[SVC_PROTO_MAX_FRAME];   /* 线缆格式字节 */
} svc_uart_tx_frame_t;

/**
 * @brief 端口收发统计
 * @note 只增不减，掉电清零；用来区分"没数据"和"丢数据"。
 */
typedef struct {
    uint32_t rx_bytes;      /* 累计收到的字节数 */
    uint32_t rx_frames;     /* 累计解出的帧数 */
    uint32_t rx_dropped;    /* 帧队列满而丢弃的帧数 */
    uint32_t rx_checksum;   /* 校验失败丢弃的帧数 */
    uint32_t rx_timeout;    /* 半帧超时重置的次数 */
    uint32_t rx_overflow;   /* BSP 字节队列溢出丢弃的字节数 */
    uint32_t tx_frames;     /* 累计提交发送的帧数 */
    uint32_t tx_dropped;    /* 发送队列满而丢弃的帧数 */
    uint32_t tx_timeout;    /* 等待 DMA 完成超时的次数 */
} svc_uart_stat_t;

/*==============================================================================
 * 初始化
 *============================================================================*/
/**
 * @brief 初始化链路服务并启动所有端口
 * @retval 0: 成功
 * @retval -1: BSP 初始化或 DMA 启动失败
 * @note 必须在 OS 对象创建之后、第一个线程启动之前调用
 *       （CubeMX 工程放在 freertos.c 的 RTOS_QUEUES 段）。
 */
int Svc_Uart_Init(void);

/*==============================================================================
 * 接收
 *============================================================================*/
/**
 * @brief 等一次接收通知并排空所有端口
 * @param now_ms 当前系统节拍（ms），由调用方传入
 * @retval 无
 * @note 最多阻塞 SVC_UART_RX_POLL_MS 就返回：有中断通知时立即处理突发数据，
 *       没有通知时也按周期补搬一次（几毫秒才来一帧的慢速链路不会触发
 *       半满/全满中断，全靠这个周期兜底）。一次调用把所有端口都读干净，
 *       所以中断通知丢了也不会把数据留在队列里。
 *       时间由调用方传进来（Service 自己不看时钟），用来判断半帧挂了多久。
 *       只给 RX 任务调用，其他线程不要碰。
 */
void Svc_Uart_Rx_Poll(uint32_t now_ms);

/**
 * @brief 取一帧已解出的数据（阻塞）
 * @param frame 输出缓冲，不可为 NULL
 * @retval 0: 取到一帧
 * @retval -1: 参数非法
 * @note 阻塞直到帧队列非空；只给 CMD 任务调用。
 */
int Svc_Uart_Frame_Get(svc_proto_frame_t *frame);

/*==============================================================================
 * 发送
 *============================================================================*/
/**
 * @brief 打包并提交一帧发送
 * @param id      目标端口编号（1 起），不存在则丢弃
 * @param cmd     命令字
 * @param payload 载荷，len 为 0 时可为 NULL
 * @param len     载荷长度，0 ~ SVC_PROTO_MAX_PAYLOAD
 * @retval 0: 已提交
 * @retval -1: 参数非法或队列满
 * @note 非阻塞：只入队，真正发出由 TX 任务完成。
 *       可在任务上下文调用；不要在中断里调用。
 */
int Svc_Uart_Send(uint8_t id, uint8_t cmd, const uint8_t *payload, uint8_t len);

/**
 * @brief 取一帧并交给 DMA 发出，等发送完成（阻塞）
 * @retval 无
 * @note 只给 TX 任务调用。内置"清残留完成信号 → 启动 → 等完成"的时序，
 *       避免上一帧的完成信号被误当成这一帧的。
 */
void Svc_Uart_Tx_Pump(void);

/*==============================================================================
 * 诊断
 *============================================================================*/
/**
 * @brief 取指定端口的统计
 * @param id 端口编号（1 起）
 * @retval 非 NULL: 统计结构（只读，不要释放）
 * @retval NULL: 端口不存在
 */
const svc_uart_stat_t *Svc_Uart_Stat(uint8_t id);

#endif /* __Svc_Uart_H__ */
