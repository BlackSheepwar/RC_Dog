/**
 * @file task_uart_tx.c
 * @brief 串口发送线程：取一帧、交给 DMA、等发送完成
 * @author Ricardo
 * @date 2026-10-31
 *
 * @note 帧间不会出现"轮询忙标志 + osDelay(1)"的空档：
 *       发送完成的同步在 Service 层用信号量做，本线程只负责驱动泵。
 */

/*==============================================================================
 * 头文件包含
 *============================================================================*/
// 固定包含
#include <stdint.h>
#include "svc_uart.h"

/*==============================================================================
 * 线程函数
 *============================================================================*/
/**
 * @brief 串口发送线程
 * @param argument 线程参数（未使用）
 * @retval 无
 * @note 阻塞在 Svc_Uart_Tx_Pump() 内：没有待发帧时睡眠，
 *       有帧则发出并等 DMA 完成，因此不会与下一帧抢 DMA 通道。
 */
void Task_UART_TX(void *argument)
{
    (void)argument;

    for (;;)
    {
        Svc_Uart_Tx_Pump();
    }
}
