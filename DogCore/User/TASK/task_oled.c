/**
 * @file task_oled.c
 * @brief OLED 线程：刷新帧率显示
 * @author Ricardo
 * @date 2026-11-01
 *
 * @note 面板初始化与 UI 状态都在 freertos.c 的 RTOS_MUTEX 段里做完：
 *       OLED 走 I2C，要等 IIC_LOCK 互斥量就位；整屏初始化约 23 ms，
 *       放在调度前，线程里就只剩刷屏。
 */

/*==============================================================================
 * 头文件包含
 *============================================================================*/
// 固定包含
#include <stdint.h>
#include "cmsis_os2.h"
// 功能包含
#include "oled.h"
#include "oled_extend.h"
#include "oled_ui.h"

/*==============================================================================
 * 宏定义与常量
 *============================================================================*/
/** @brief 刷屏周期（ms） */
#define TASK_OLED_PERIOD_MS     1u

/*==============================================================================
 * 线程函数
 *============================================================================*/
/**
 * @brief OLED 显示线程（入口名由 CubeMX .ioc 决定，不能改）
 * @param argument 线程参数（未使用）
 * @retval 无
 */
void Task_OLED(void *argument)
{
    (void)argument;

    for (;;) {
        OLED_UI_FpsTick();
        osDelay(TASK_OLED_PERIOD_MS);
    }
}
