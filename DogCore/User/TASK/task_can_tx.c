/**
 * @file task_can_tx.c
 * @brief CAN 发送线程：周期把软件缓冲推进硬件邮箱
 * @author Ricardo
 * @date 2026-11-01
 *
 * @note 改用"周期排空"而不是"发送完成信号量唤醒"：
 *       硬件邮箱 3 个，1 ms 排一次足够跑满 1200 fps，
 *       而信号量那套要求 BSP 的发送完成中断去释放、APP 去释放，
 *       两边都得认识 OS 对象，反而把分层搞脏。
 *       现在只有 TASK 碰 OS，BSP / Service / APP 都不碰。
 */

/*==============================================================================
 * 头文件包含
 *============================================================================*/
// 固定包含
#include <stdint.h>
#include "cmsis_os2.h"
// 功能包含
#include "app_can.h"

/*==============================================================================
 * 宏定义与常量
 *============================================================================*/
/** @brief 排空周期（ms） */
#define TASK_CAN_TX_PERIOD_MS       1u

/*==============================================================================
 * 线程函数
 *============================================================================*/
/**
 * @brief CAN 发送线程（入口名由 CubeMX .ioc 决定，不能改）
 * @param argument 线程参数（未使用）
 * @retval 无
 * @note 没有待发帧时只是空转一圈，代价是一次函数调用加一次下标判断。
 */
void Task_CAN_TX(void *argument)
{
    (void)argument;

    for (;;) {
        APP_CAN_Flush();
        osDelay(TASK_CAN_TX_PERIOD_MS);
    }
}
