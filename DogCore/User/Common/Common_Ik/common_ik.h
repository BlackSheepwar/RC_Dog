/**
 * @file common_ik.h
 * @brief 二连杆逆运动学（平面）：足端坐标 → 髋/膝角度，纯数学
 * @author Ricardo
 * @date 2026-11-01
 *
 * @note 这是全工程唯一的二连杆解算实现，属于 Common 横向层：
 *       只知道杆长与坐标，不知道腿装在哪、舵机多少度、步态怎么排。
 *       因此可以在 PC 上直接喂数据单测，也可以给机械同事当公式验算工具。
 *
 *       坐标系（数学系）：+x 前、+y 上、原点在髋关节（杆1 的转轴）。
 *       用户数据（+x 前、+y 下）在调用前自己取反 y，本模块不掺和业务约定。
 *
 *       二连杆有两组解（膝向后 / 膝向前），两组都物理可达，
 *       选哪一组是产品姿态问题，所以本模块只负责"都给出来"，
 *       由上层按自己的装配方向挑索引。
 *
 *       角度单位一律为度（°），长度单位由调用方保证一致（mm 或 m 都行）。
 */

#ifndef __Common_Ik_H__
#define __Common_Ik_H__

/*==============================================================================
 * 头文件包含
 *============================================================================*/
// 固定包含
#include <stdint.h>

/*==============================================================================
 * 类型定义
 *============================================================================*/
/**
 * @brief 二连杆杆长（值类型：一条腿一份，按值传给解算函数）
 * @note 只放几何参数，不放角度与状态——本模块没有状态。
 */
typedef struct {
    float l1;   /* 杆1（大腿）长度，必须 > 0 */
    float l2;   /* 杆2（小腿）长度，必须 > 0 */
} common_ik_link_t;

/**
 * @brief 逆解结果（值类型：调用方按值持有）
 * @note 两组解按膝关节弯曲方向排列：
 *       [0] 膝向后（θ2 ≥ 0），[1] 膝向前（θ2 ≤ 0）；
 *       边界奇异时两组数值相同、count = 1；不可达时 count = 0、角度为 0。
 */
typedef struct {
    float   hip[2];     /* 髋关节角度（度） */
    float   knee[2];    /* 膝关节角度（度） */
    uint8_t count;      /* 有效解的个数：0 / 1 / 2 */
} common_ik_solution_t;

/*==============================================================================
 * 逆解：坐标 → 角度
 *============================================================================*/
/**
 * @brief 二连杆逆解，返回两组（或一/零组）关节角
 * @param link 杆长，不可为 NULL；l1、l2 必须 > 0
 * @param x    足端 x 坐标（+x 前）
 * @param y    足端 y 坐标（+y 上）
 * @param out  解算结果，不可为 NULL
 * @retval -1: 参数非法（空指针或杆长非正），out 已清零
 * @retval 0: 不可达（足端超出工作空间），out 已清零
 * @retval 1: 边界奇异，只有一组解（足端正好在杆长和/差上）
 * @retval 2: 两组解（膝前、膝后均可到达）
 * @note 求解步骤：
 *       1. d² = x² + y²，判断 d 是否落在 [|l1−l2|, l1+l2]；
 *       2. 余弦定理求 cosθ2，钳位到 [−1, 1] 防浮点越界；
 *       3. θ2 = ±acos(cosθ2)，得两组；
 *       4. θ1 = atan2(y, x) − atan2(l2·sinθ2, l1 + l2·cosθ2)；
 *       5. 弧度转角度。
 */
int Common_Ik_Solve(const common_ik_link_t *link, float x, float y,
                    common_ik_solution_t *out);

/*==============================================================================
 * 正解：角度 → 坐标（校验与标定用）
 *============================================================================*/
/**
 * @brief 二连杆正解：给定关节角求足端坐标
 * @param link 杆长，不可为 NULL；l1、l2 必须 > 0
 * @param hip  髋关节角度（度）
 * @param knee 膝关节角度（度）
 * @param x    输出足端 x 坐标，可为 NULL（不需要就不取）
 * @param y    输出足端 y 坐标，可为 NULL
 * @retval 0: 成功
 * @retval -1: 杆长为空或非正
 * @note 与 Common_Ik_Solve 严格互逆：把解出来的角度喂回来应当得到原坐标。
 *       现场的步态表写的是坐标，改杆长后用它验一遍最省事。
 */
int Common_Ik_Solve_Forward(const common_ik_link_t *link, float hip, float knee,
                            float *x, float *y);

#endif /* __Common_Ik_H__ */
