/**
 * @file common.h
 * @brief 平台无关的通用定义：数组长度、限幅宏、通用返回码
 * @author Ricardo
 * @date 2026-11-01
 *
 * @note Common 是横向层：谁都能用，它不依赖任何人。
 *       本文件只放纯 C 的东西——没有 HAL、没有 OS、没有句柄，
 *       因此可以原样拿到 PC 上编译并单测。
 */

#ifndef __Common_Utils_H__
#define __Common_Utils_H__

/*==============================================================================
 * 头文件包含
 *============================================================================*/
// 固定包含
#include <stdint.h>
#include <stddef.h>

/*==============================================================================
 * 宏定义与常量
 *============================================================================*/
/**
 * @brief 取静态数组的元素个数
 * @note 只能用于真正的数组：传指针进来会得到 sizeof(指针)/sizeof(元素)，
 *       编译期不报错，属于调用方责任。
 */
#define ARRAY_SIZE(arr)     (sizeof(arr) / sizeof((arr)[0]))

/**
 * @brief 把 value 限幅到 [lo, hi]
 * @note 参数会被求值两次，不要传带副作用的表达式（如 i++）。
 */
#define COMMON_CLAMP(value, lo, hi) \
    (((value) < (lo)) ? (lo) : (((value) > (hi)) ? (hi) : (value)))

/*==============================================================================
 * 类型定义
 *============================================================================*/
/**
 * @brief 通用返回码
 * @note 0 成功、负值失败，与 HAL/BSP 的约定一致，上层统一写 `if (ret < 0)`。
 */
typedef enum {
    ERR_OK      =  0,    /* 成功 */
    ERR_PARAM   = -1,    /* 参数非法 */
    ERR_BUSY    = -2,    /* 资源忙 */
    ERR_TIMEOUT = -3,    /* 超时 */
    ERR_LOCKED  = -4,    /* 全局锁定（急停/致命错误） */
    ERR_UNKNOWN = -5,    /* 未知错误 */
} error_code_t;

#endif /* __Common_Utils_H__ */
