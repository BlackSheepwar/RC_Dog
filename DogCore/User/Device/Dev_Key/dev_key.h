/**
 * @file dev_key.h
 * @brief 按键设备层：一个按键一个句柄，只回答"现在按没按下"
 * @author Ricardo
 * @date 2026-11-01
 *
 * @note 本层不知道什么是"短按""长按""消抖"——那是 Svc_Key_Logic 的事；
 *       也不做任何延时与重试，只把 bsp_gpio 的电平按极性翻译成逻辑状态。
 *
 *       句柄只存"下层句柄指针 + 极性"，端口号与引脚号一律不进本层。
 */

#ifndef __Dev_Key_H__
#define __Dev_Key_H__

/*==============================================================================
 * 头文件包含
 *============================================================================*/
// 固定包含
#include <stdint.h>

/*==============================================================================
 * 类型定义
 *============================================================================*/
/**
 * @brief 按键句柄（不透明类型，布局在 dev_key.c）
 */
typedef struct dev_key dev_key_t;

/*==============================================================================
 * 外部声明：一个物理按键一份句柄
 *============================================================================*/
/** @brief 板载按键（PC13，CubeMX 配下拉，按下为高电平） */
extern const dev_key_t dev_key_1;

/*==============================================================================
 * 接口
 *============================================================================*/
/**
 * @brief 按键设备层初始化（校验极性配置）
 * @retval 0: 成功
 * @retval -1: 句柄表里有空指针
 * @note 引脚模式由 MX_GPIO_Init() 配好，这里不做硬件初始化，
 *       只做一次配置自检，早失败比运行时瞎猜好。
 */
int Dev_Key_Init(void);

/**
 * @brief 判断按键当前是否按下
 * @param key 按键句柄，可为 NULL
 * @retval 1: 已按下（已按 active_low 换算成逻辑状态）
 * @retval 0: 未按下，或句柄为 NULL
 * @note 返回的是"此刻的电平"，没有消抖；连续采样与判定请看 Svc_Key_Logic。
 */
uint8_t Dev_Key_Is_Pressed(const dev_key_t *key);

#endif /* __Dev_Key_H__ */
