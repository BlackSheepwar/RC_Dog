/**
 * @file oled_ui.h
 * @brief OLED 显示 UI 组件：帧率测试 + 串口压力测试显示
 * @author
 * @date 2026-06-25
 *
 * @note 本模块封装两个功能：
 *       1. OLED_UI_FpsTick() — 帧率显示，替代 task_oled.c 中的手写循环
 *       2. OLED_UI_ShowStressTest() — 串口回环压力测试结果显示
 *
 *       两者独立，使用者按需调用。每次调用独占全屏。
 */

#ifndef __OLED_UI_H__
#define __OLED_UI_H__

/*==============================================================================
 * 头文件包含
 *============================================================================*/
#include <stdint.h>

/*==============================================================================
 * FPS 帧率显示
 *============================================================================*/
/**
 * @brief 初始化 FPS 计数器（每次复位后调用一次）
 */
void OLED_UI_FpsInit(void);

/**
 * @brief FPS 帧率刷新（按实际调用频率计算 FPS）
 * @note 内部调用 OLED_NewFrame + 绘图 + OLED_ShowFrame，
 *       每次调用独占全屏，不要在外层重复调用这些函数。
 *       建议放在主循环中调用，osDelay(1) 间隔。
 */
void OLED_UI_FpsTick(void);

/*==============================================================================
 * 编码器计数值显示（PID 调参用）
 *============================================================================*/
/**
 * @brief 初始化编码器计数显示（复位所有编码器计数器）
 * @note 调用 BSP_Encoder_Reset 清零全部 4 路编码器，
 *       确保显示从 0 开始累积。
 */
void OLED_UI_EncoderInit(void);

/**
 * @brief 编码器计数值刷新（显示 4 路编码器的累积计数值）
 * @note  每次调用独占全屏。
 *        读取当前计数值（不自动清零），适合手动旋转电机
 *        一圈后观察计数增量，用于确定编码器线数/PID 调速参数。
 *
 *        屏幕布局（128x64，afont16x8 字体）：
 *          E1: ±nnnnn
 *          E2: ±nnnnn
 *          E3: ±nnnnn
 *          E4: ±nnnnn
 */
void OLED_UI_EncoderTick(void);

#endif /* __OLED_UI_H__ */
