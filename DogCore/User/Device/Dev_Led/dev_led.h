/**
 * @file dev_led.h
 * @brief 指示灯设备层：一颗灯一个句柄，只回答"亮还是灭"
 * @author Ricardo
 * @date 2026-11-01
 *
 * @note 亮灭与电平的对应关系（高电平点亮还是低电平点亮）收在句柄里，
 *       业务层只管说"亮"或"灭"，不再关心硬件接法。
 */

#ifndef __Dev_LED_H__
#define __Dev_LED_H__

/*==============================================================================
 * 头文件包含
 *============================================================================*/
// 固定包含
#include <stdint.h>

/*==============================================================================
 * 类型定义
 *============================================================================*/
/**
 * @brief 指示灯句柄（不透明类型，布局在 dev_led.c）
 */
typedef struct dev_led dev_led_t;

/*==============================================================================
 * 外部声明
 *============================================================================*/
/** @brief 板载指示灯（PE3） */
extern const dev_led_t dev_led_0;

/*==============================================================================
 * 接口
 *============================================================================*/
/**
 * @brief 设置灯的亮灭
 * @param led 灯句柄，可为 NULL
 * @param on  1 点亮，0 熄灭
 * @retval 无
 * @note 极性换算在实现里完成；句柄为 NULL 时直接返回。
 */
void Dev_LED_Set(const dev_led_t *led, uint8_t on);

/**
 * @brief 翻转灯的亮灭
 * @param led 灯句柄，可为 NULL
 * @retval 无
 * @note 只用于单写者场景（读状态再写）。
 */
void Dev_LED_Toggle(const dev_led_t *led);

/**
 * @brief 查询灯是否处于点亮状态
 * @param led 灯句柄，可为 NULL
 * @retval 1: 点亮
 * @retval 0: 熄灭，或句柄为 NULL
 */
uint8_t Dev_LED_Is_On(const dev_led_t *led);

#endif /* __Dev_LED_H__ */
