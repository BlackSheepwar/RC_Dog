/**
 * @file pid.h
 * @brief 增量式 PID 闭环控制算法（纯算法，无硬件依赖）
 * @author 李嘉图
 * @date 2026-07-05
 *
 * @note 本层只做数学运算，不涉及任何硬件或平台相关内容。
 *       状态由调用方维护（传入 PID_Handle_t 指针），
 *       可在任意平台复用（STM32、ESP32、PC仿真等）。
 *       仅保留增量式 PID（参考 Mini 4WD RC 实现）。
 */

#ifndef __PID_H__
#define __PID_H__

/*==============================================================================
 * 头文件包含
 *============================================================================*/
#include <stdint.h>

/*==============================================================================
 * PID 控制器句柄
 *
 * 调用方分配此结构体实例并传入各函数指针。
 * 所有状态均存放在此结构体中，本层不维护任何静态/全局变量。
 *============================================================================*/
typedef struct {
    float target;           /* 目标值                                */
    float actual;           /* 实际值（由调用方每次调度前更新）       */
    float out;              /* PID 输出值（累加值）                   */

    float Kp;               /* 比例系数                              */
    float Ki;               /* 积分系数                              */
    float Kd;               /* 微分系数（通常为 0）                   */

    float error[3];         /* 误差历史 [0]=本次, [1]=上次, [2]=上上次 */
    float out_max;          /* 输出上限（抗饱和用）                   */
    float out_min;          /* 输出下限（抗饱和用）                   */
} PID_Handle_t;

/*==============================================================================
 * 初始化函数
 *============================================================================*/
void PID_Init(PID_Handle_t *pid, float Kp, float Ki, float Kd,
              float out_max, float out_min);

/*==============================================================================
 * 参数设置
 *============================================================================*/
void PID_SetTarget(PID_Handle_t *pid, float target);
void PID_SetParam(PID_Handle_t *pid, float Kp, float Ki, float Kd);
void PID_Reset(PID_Handle_t *pid);

/*==============================================================================
 * PID 控制核心
 *============================================================================*/
/**
 * @brief 增量式 PID 控制
 * @param pid    PID 句柄指针
 * @param actual 当前实际值（如编码器换算速度）
 * @return PID 输出增量
 * @note Δu = Kp·Δe + Ki·e + Kd·(Δe − Δe_prev)
 *       其中 Δe = e(t) − e(t−1), Δe_prev = e(t−1) − e(t−2)
 *       Ki/Kd 项不带 dt（与 Mini 4WD RC 一致）
 *       返回值是增量，out 内部累加并限幅，调用方直接用 pid->out
 */
float PID_IncrementControl(PID_Handle_t *pid, float actual);

#endif /* __PID_H__ */
