/**
 * @file app_motor_debug.h
 * @brief 电机 PID 调参数据发送（调试用，与 PID 控制器解耦）
 * @author 李嘉图
 * @date 2026-07-07
 *
 * @note 本模块独立于 PID 控制逻辑，仅用于开发阶段的参数整定。
 *       通过 APP_Motor_GetPIDState 读取各电机 PID 状态，
 *       格式化为串口绘图仪兼容格式后发送。
 *       正式固件可整体移除本模块，不影响电机控制功能。
 */

#ifndef __APP_MOTOR_DEBUG_H__
#define __APP_MOTOR_DEBUG_H__

/*==============================================================================
 * 头文件包含
 *============================================================================*/
#include <stdint.h>

/*==============================================================================
 * 调参数据发送
 *============================================================================*/
/**
 * @brief 发送所有电机的 PID 调参数据（串口绘图仪兼容格式）
 * @param uart_id 串口编号（与 BSP 层一致）
 * @note  格式: "PID: T1,A1,O1,T2,A2,O2,T3,A3,O3,T4,A4,O4\n"
 *        共 12 通道: 每电机 3 值（目标/实际/输出），\n 结尾。
 *        兼容 SerialPlot / Arduino 串口绘图仪等采样数据解析工具。
 */
void APP_Motor_SendPIDData(uint8_t uart_id);

#endif /* __APP_MOTOR_DEBUG_H__ */
