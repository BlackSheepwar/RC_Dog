/**
 * @file app_uart.h
 * @brief 串口业务层：命令字 → 产品动作，以及全局发送出口
 * @author Ricardo
 * @date 2026-11-01
 *
 * @note APP 只做两件事：把命令字映射成动作（命令表在 app_uart_cmd.c），
 *       以及给其他 APP 模块一个统一的发送出口。
 *       字节怎么收、帧怎么解、DMA 什么时候启动，全部在 Service 层。
 */

#ifndef __APP_UART_H__
#define __APP_UART_H__

/*==============================================================================
 * 头文件包含
 *============================================================================*/
// 固定包含
#include <stdint.h>
#include "svc_uart.h"           /* svc_uart_tx_frame_t */

/*==============================================================================
 * 宏定义与常量
 *============================================================================*/
/** @brief 链路 1（UART4）。协议层只认编号，不认芯片引脚 */
#define APP_UART_PORT_1     1u
/** @brief 链路 2（UART5）。按键测试命令走这一路 */
#define APP_UART_PORT_2     2u

/*==============================================================================
 * 类型定义
 *============================================================================*/
/**
 * @brief 发送帧类型别名
 * @note CubeMX 生成的 freertos.c 用这个名字创建 UART_TX_Q
 *       （osMessageQueueNew(16, sizeof(APP_TxFrame_t), ...)）。
 *       这里别名到服务层的帧结构，避免生成代码与手写代码各存一份定义；
 *       改名会牵动生成代码，所以保留旧名字。
 */
typedef svc_uart_tx_frame_t APP_TxFrame_t;

/*==============================================================================
 * 命令分发
 *============================================================================*/
/**
 * @brief 按命令字查表并执行
 * @param cmd     命令字
 * @param payload 载荷，可为 NULL（取决于命令定义）
 * @param len     载荷长度
 * @retval 无
 * @note 命令表见 app_uart_cmd.c；未定义的命令字静默忽略。
 */
void APP_UART_Cmd(uint8_t cmd, uint8_t *payload, uint8_t len);

/*==============================================================================
 * 发送
 *============================================================================*/
/**
 * @brief 向指定链路发送一帧命令
 * @param id      目标链路，取 APP_UART_PORT_x
 * @param cmd     命令字
 * @param payload 载荷，len 为 0 时可为 NULL
 * @param len     载荷长度，0 ~ SVC_PROTO_MAX_PAYLOAD
 * @retval 0: 已提交发送队列
 * @retval -1: 参数非法或队列满
 * @note 任务上下文调用，不阻塞等待发送完成。
 */
int APP_UART_Send(uint8_t id, uint8_t cmd, const uint8_t *payload, uint8_t len);

#endif /* __APP_UART_H__ */
