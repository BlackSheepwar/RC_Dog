/*==============================================================================
 * 头文件包含
 *============================================================================*/
// 固定包含
#include <stdint.h>
#include "main.h"               /* HAL_GetTick */
#include "bsp_sys.h"

/*==============================================================================
 * 时间基准
 *============================================================================*/
/**
 * @brief 取系统毫秒计数
 * @retval 上电以来的毫秒数（约 49.7 天回绕）
 */
uint32_t BSP_SYS_Get_Tick_Ms(void)
{
    return HAL_GetTick();
}
